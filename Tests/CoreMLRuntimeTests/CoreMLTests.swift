@Suite struct GemmaTokenizerTests {
    struct Fixture: Decodable { let text: String; let expected: [Int32]; let raw: [Int32] }
    static let modelFolder = (ProcessInfo.processInfo.environment["NEURALSPOTLIGHT_COREML_MODELS"] ?? ProcessInfo.processInfo.environment["DIGUP_COREML_MODELS"]).map { URL(fileURLWithPath: $0) }
        ?? URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent().appendingPathComponent(".dev/models/CoreML")
    static let present = FileManager.default.fileExists(atPath: modelFolder.appendingPathComponent("tokenizer.json").path)

    /// Generated by Hugging Face tokenizers from the pinned tokenizer.json: Korean, canonical Unicode variants,
    /// leading BOM, byte fallback, whitespace, literal special tokens and code. No model inference is needed.
    @Test(.enabled(if: present)) func matchesHuggingFaceTokenizer() throws {
        let tokenizer = try GemmaTokenizer(tokenizerJsonURL: Self.modelFolder.appendingPathComponent("tokenizer.json"))
        let file = URL(fileURLWithPath: #filePath).deletingLastPathComponent().appendingPathComponent("Reference/tokenizer.json")
        let fixtures = try JSONDecoder().decode([Fixture].self, from: Data(contentsOf: file))
        for fixture in fixtures {
            #expect(tokenizer.tokenize(fixture.text) == fixture.raw, "\(fixture.text)")
            #expect(tokenizer.encode(fixture.text, maxLength: 512) == fixture.expected, "\(fixture.text)")
        }
        let truncated = tokenizer.encode(String(repeating: "hello ", count: 1000), maxLength: 512)
        #expect(truncated.count == 512)
        #expect(truncated.first == tokenizer.bosId && truncated.last == tokenizer.eosId)
    }
}

/// Opt in with NEURALSPOTLIGHT_TEST_COREML=1. The first load compiles the actual model for this device and can take minutes.
@Suite(.enabled(if: (ProcessInfo.processInfo.environment["NEURALSPOTLIGHT_TEST_COREML"] ?? ProcessInfo.processInfo.environment["DIGUP_TEST_COREML"]) == "1"))
struct CoreMLInferenceTests {
    @Test func actualModelAgreesWithReferenceAndRetainsLongDocumentTail() throws {
        let start = Date()
        let model = try CoreMLTextEmbedder(folder: GemmaTokenizerTests.modelFolder, textOnly: false)
        defer { model.close() }
        struct Reference: Decodable { let vectors: [String: [Float]] }
        let referenceURL = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
            .appendingPathComponent("Reference/media/vectors.json")
        let reference = try JSONDecoder().decode(Reference.self, from: Data(contentsOf: referenceURL))
        let examples: [(String, String)] = [
            ("query", Prompts.query("payment declined error")),
            ("query-bn", Prompts.query("ইলিশ মাছ রান্না")),
            ("query-ar", Prompts.query("متى تغلق المكتبة")),
            ("document", Prompts.document(title: "Tokyo itinerary", text: "Flight to Tokyo Haneda on November 3. Then the "
                + "train to Kamakura to see the Great Buddha, and back for dinner in Shibuya.")),
        ]
        let values = try model.embedTexts(examples.map(\.1))
        for ((name, _), vector) in zip(examples, values) {
            let expected = try #require(reference.vectors[name])
            let cosine = zip(vector, expected).reduce(Float(0)) { $0 + $1.0 * $1.1 }
            print("Core ML reference \(name): cosine=\(cosine)")
            #expect(vector.count == 768)
            #expect(vector.allSatisfy { $0.isFinite })
            #expect(cosine >= 0.997, "\(name): \(cosine)")
        }
        let prefix = String(repeating: "We reviewed the meeting notes and agreed on the next steps. ", count: 90)
        let tail = String(repeating: "This section describes neural networks and GPU matrix multiplication. ", count: 90)
        let long = try model.embedTexts([Prompts.document(title: nil, text: prefix),
                                         Prompts.document(title: nil, text: prefix + tail)])
        let agreement = zip(long[0], long[1]).reduce(Float(0)) { $0 + $1.0 * $1.1 }
        #expect(agreement < 0.995, "Tail content must affect a document beyond the first 512 tokens")
        model.close()
        #expect(throws: CoreMLError.self) { try model.embedTexts(["closed"]) }
        print("Core ML actual model test: \(Date().timeIntervalSince(start)) seconds including load/compile")
    }
}

@Test func tokenizerKeepsUnicodeBytesAndAddedTokenBoundaries() throws {
    // A small BPE vocabulary deliberately contains canonically equivalent, byte-distinct Unicode tokens.
    let source = #"""
    {
      "added_tokens":[{"id":2,"content":"<bos>","single_word":false,"lstrip":false,"rstrip":false,"normalized":false}],
      "model":{
        "vocab":{"<pad>":0,"<eos>":1,"<bos>":2,"<unk>":3,"▁":4,"a":5,"b":6,"ab":7,"▁a":8,
                 "é":9,"e":10,"\u0301":11,"e\u0301":12,"\ufeff":13,"#":14,"\ufeff#":15},
        "merges":[["a","b"],["▁","a"],["e","\u0301"],["\ufeff","#"]]
      }
    }
    """#
    let tokenizer = try GemmaTokenizer(data: Data(source.utf8))
    #expect(tokenizer.tokenize("ab a") == [7, 8])
    #expect(tokenizer.tokenize("é e\u{301}") == [9, 4, 12])
    #expect(tokenizer.tokenize("\u{feff}#") == [15])
    #expect(tokenizer.tokenize("a<bos>b") == [5, 2, 6])
    #expect(tokenizer.encode("ab ab", maxLength: 4) == [2, 7, 4, 1])
    #expect(throws: CoreMLError.self) { try GemmaTokenizer(data: Data("{}".utf8)) }
}

@Test func longDocumentsRetainEveryBodyTokenAndRepeatPrefix() {
    let prefix: [Int32] = [1, 2, 3, 4]
    let body = (100..<1800).map(Int32.init)
    let windows = CoreMLTextEmbedder.windows(tokens: prefix + body, prefixCount: prefix.count)
    #expect(windows.count == 4)
    #expect(windows.allSatisfy { $0.tokens.count <= 510 && Array($0.tokens.prefix(4)) == prefix })
    #expect(windows.flatMap { $0.tokens.dropFirst(4) } == body)
    #expect(windows.map(\.weight).reduce(0, +) == body.count)
    #expect(CoreMLTextEmbedder.documentPrefix("title: My code | text: hello") == "title: My code | text:")
    #expect(CoreMLTextEmbedder.documentPrefix("title: none | text:") == "title: none | text:")
    #expect(CoreMLTextEmbedder.documentPrefix("unprompted content") == "")
}

@Test func weightedWindowsAreNormalizedAndRejectBrokenPredictions() throws {
    let value = try CoreMLTextEmbedder.combine([[1, 0], [0, 1]], weights: [3, 4])
    #expect(abs(value[0] - 0.6) < 0.00001)
    #expect(abs(value[1] - 0.8) < 0.00001)
    #expect(throws: CoreMLError.self) { try CoreMLTextEmbedder.normalized([0, 0]) }
    #expect(throws: CoreMLError.self) { try CoreMLTextEmbedder.normalized([.nan, 0]) }
    #expect(throws: CoreMLError.self) { try CoreMLTextEmbedder.combine([[1], [1, 2]], weights: [1, 1]) }
}

